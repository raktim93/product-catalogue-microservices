create table outbox_events (
    id           bigint generated by default as identity primary key,   -- also the sending order
    event_id     uuid        not null,
    aggregate_id bigint      not null,      -- the product id: the Kafka key
    event_type   varchar(40) not null,
    payload      text        not null,      -- the event JSON, exactly as it will be sent
    created_at   timestamp   not null,
    published_at timestamp                  -- null = not sent yet
);

create index idx_outbox_events_unpublished on outbox_events (published_at, id);